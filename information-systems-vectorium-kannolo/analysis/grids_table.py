#!/usr/bin/env python3
"""The parameter grid of every system, as a LaTeX longtable for the supplementary material.

Dense grids are read from dense/vibe/definitions (what run_dense.py runs), sparse grids from
sparse/grids.py (what run_sparse.py runs).

    python analysis/grids_table.py <out.tex>
"""

import os
import sys

import yaml

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "sparse"))

# (definitions directory, VIBE algorithm name, row label), in the paper's order.
DENSE = [
    ("kannolo", "kannolo", r"\kannolohnsw"),
    ("kannolo_rerank", "kannolo-rerank", r"\kannolorerank"),
    ("hnswlib", "hnswlib", r"\hnswlib"),
    ("glass", "glass", r"\glass"),
    ("symphonyqg", "symphonyqg", r"\symphonyqg"),
    ("lorann", "lorann", r"\lorann"),
    ("rabitq", "rabitq-hnsw", r"\rabitqhnsw"),
    ("svs", "vamana-leanvec(svs)", r"\svsleanvec"),
]
# Names of positional build arguments (`arg_groups`), after the metric.
ARG_GROUP_NAMES = {"kannolo-rerank": ["m", "ef_construction", "graph_type", "first-stage encoder"]}
ENCODER = {("rabitq", 1): "RaBitQ 1-bit", ("rabitq-ext", 2): "RaBitQ-ext 2-bit",
           ("rabitq-ext", 4): "RaBitQ-ext 4-bit"}


def tex(s):
    return str(s).replace("_", r"\_").replace("%", r"\%")


def fmt(v):
    if v is None:
        return "off"
    if isinstance(v, tuple):
        return "(" + ", ".join(fmt(x) for x in v) + ")"
    if isinstance(v, bool):
        return str(v).lower()
    if isinstance(v, list) and len(v) == 4 and v[0] in ("rabitq", "rabitq-ext"):
        return ENCODER[(v[0], 1 if v[0] == "rabitq" else v[2])]
    return f"{v:g}" if isinstance(v, float) else str(v)


def axis(name, values):
    if all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in values):
        values = sorted(values)
    elif None in values:
        values = [None] + sorted(v for v in values if v is not None)
    return rf"{tex(name)} $\in$ \{{{', '.join(tex(fmt(v)) for v in values)}\}}"


def search_axes(group):
    q = group.get("query_args", {})
    if isinstance(q, dict):
        return [axis(k, v) for k, v in q.items()]
    # LoRANN: a list of paired settings
    pairs = q[0]
    keys = list(pairs[0])
    return [rf"({', '.join(tex(k) for k in keys)}) $\in$ \{{"
            + ", ".join("(" + ", ".join(fmt(p[k]) for k in keys) + ")" for p in pairs) + r"\}"]


def build_axes(name, group):
    if "arg_groups" in group:
        return [axis(n, v) for n, v in zip(ARG_GROUP_NAMES[name], group["arg_groups"])]
    return [axis(k, v if isinstance(v, list) else [v]) for k, v in group["args"].items()]


def dense_rows():
    out = []
    for d, name, label in DENSE:
        cfg = yaml.safe_load(open(os.path.join(REPO, "dense", "vibe", "definitions", d, "config.yml")))
        algo = next(a for a in cfg["float"]["any"] if a["name"] == name)
        groups = list(algo["run_groups"].values())
        for i, g in enumerate(groups):
            out.append((label if i == 0 else "", "; ".join(build_axes(name, g)),
                        "; ".join(search_axes(g))))
    return out


def arms_text(arms):
    """One product per line; constant parameters are written once."""
    return r" \newline ".join("; ".join(axis(k, v) for k, v in arm.items()) for arm in arms)


def sparse_rows():
    import grids
    out = []
    for system, label in grids.TABLE_ORDER:
        for i, (collections, build, search) in enumerate(grids.table_blocks(system)):
            out.append((label if i == 0 else "", collections, arms_text(build), arms_text(search)))
    return out


def main():
    lines = [r"% Generated by kannolo-bench-paper/analysis/grids_table.py -- do not edit by hand.",
             r"\subsection*{Dense collections}",
             r"Every grid is the same on the four dense collections.",
             r"\begin{longtable}{@{}l>{\raggedright\arraybackslash}p{0.38\linewidth}"
             r">{\raggedright\arraybackslash}p{0.38\linewidth}@{}}",
             r"\toprule", r"System & Build parameters & Search parameters \\", r"\midrule", r"\endhead"]
    lines += [rf"{a} & {b} & {c} \\" for a, b, c in dense_rows()]
    lines += [r"\bottomrule", r"\end{longtable}", "",
              r"\subsection*{Sparse collections}",
              r"\begin{longtable}{@{}l>{\raggedright\arraybackslash}p{0.12\linewidth}"
              r">{\raggedright\arraybackslash}p{0.31\linewidth}>{\raggedright\arraybackslash}p{0.31\linewidth}@{}}",
              r"\toprule", r"System & Collections & Build parameters & Search parameters \\",
              r"\midrule", r"\endhead"]
    lines += [rf"{a} & {b} & {c} & {d} \\" for a, b, c, d in sparse_rows()]
    lines += [r"\bottomrule", r"\end{longtable}"]
    with open(sys.argv[1], "w") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
