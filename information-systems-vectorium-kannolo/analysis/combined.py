"""The paper's Section 6 tables and figures, over every collection of one series at once.

    python analysis/combined.py --series dense --out-dir <out> --table-dir <out> \
        --selection agnews=selections/dense_agnews.json msmarco-qwen=... dpr=... laion=...

Reads selections written by `select_configs.py`. Writes `results_<series>.tex` (QPS, footprint
and build time at 90/95/99, one block per collection), `configs_<series>.tex` (the configuration
behind every cell, for the supplementary material), `fig_frontier_<series>.pdf` (the frontiers
side by side) and `fig_tradeoff_<series>.pdf` (footprint against QPS at 95%, with constant
QPS-per-GiB lines).
"""

import argparse
import json
import math
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

import figlib as p1
import style as st

TARGETS = ("90", "95", "99")

COLLECTIONS = {
    "agnews":         (r"\agnews", r"\textsc{AgNews}"),
    "msmarco-qwen":   (r"\msmarcoqwen", r"\textsc{MsMarco}-\textsc{Qwen}"),
    "dpr":            (r"\dpr", r"\textsc{Dpr}"),
    "laion":          (r"\laion", r"\textsc{Laion}"),
    "msmarco-splade": (r"\msmarcosplade", r"\textsc{MsMarco}-\textsc{Splade}"),
    "nq":             (r"\nq", r"\textsc{Nq}"),
    "msmarco-lilsr":  (r"\msmarcolilsr", r"\textsc{MsMarco}-\textsc{LiLsr}"),
    "msmarco-esplade": (r"\msmarcoesplade", r"\textsc{MsMarco}-\textsc{E-Splade}"),
}

MACRO = {
    "kannolo": r"\kannolohnsw", "kannolo-rerank": r"\kannolorerank",
    "hnswlib": r"\hnswlib", "glass": r"\glass", "symphonyqg": r"\symphonyqg",
    "lorann": r"\lorann", "rabitq-hnsw": r"\rabitqhnsw", "vamana-leanvec(svs)": r"\svsleanvec",
    "kannolo-hnsw": r"\kannolohnsw", "kannolo-hnsw-rerank": r"\kannolorerank",
    "seismic": r"\seismic", "seismic-wave": r"\seismicw", "pyanns": r"\pyann",
    "sindi": r"\sindi", "lsp": r"\lsp",
    "kannolo-rerank-ext8": r"\kannolorerank{} (ext-8)",
    "lorann-plain": r"\lorann{}",
}


def tex_escape(s):
    return s.replace('\\', r'\textbackslash{}').replace('_', r'\_').replace('%', r'\%') \
            .replace('&', r'\&').replace('#', r'\#').replace('{', r'\{').replace('}', r'\}')


def config_string(algo, row):
    """The configuration as `System(build; search)`, without the harness's timing-method labels.

    Dense rows already carry a clean `name`. Sparse row names have the form
    `System-CLI({python dict})`, so they are rebuilt from `build_args` and `query_args`.
    """
    if "build_args" not in row:
        return row["name"]
    build = ", ".join(f"{k}={v}" for k, v in row["build_args"].items())
    query = row.get("query_args") or {}
    if isinstance(query, str):
        query = json.loads(query)
    search = ", ".join(f"{k}={v}" for k, v in query.items() if v is not None)
    return f"{st.DISPLAY[algo]}({build}; {search})"


NOT_REPORTED = {"kannolo-rerank-ext8-resid"}


FIRST_CLASS = {"kannolo-rerank-ext8": "kannolo-rerank"}


def rows_of(selection):
    """(algo, entries, is_variant) in legend order, variants last."""
    variants = selection.get("per_target_variants") or {}
    out = []
    for a in st.SERIES_ORDER:
        out.append((a, selection["per_target"].get(a) or {}, False))
        out += [(c, variants[c], False) for c, after in FIRST_CLASS.items()
                if after == a and variants.get(c)]
    out += [(a, variants[a], True) for a in sorted(variants)
            if variants[a] and a not in NOT_REPORTED and a not in FIRST_CLASS]
    return out


def results_table(selections, out_path):
    fields = {p1._footprint_field(sel["per_target"],
                                  [a for a in st.SERIES_ORDER if sel["per_target"].get(a)],
                                  (90, 95, 99))[0]
              for _, sel in selections}
    if len(fields) != 1:
        raise SystemExit(f"combined: the collections use different footprints: {fields}")
    fp_field = fields.pop()
    fp_head = "Memory (GiB)" if fp_field == "uss_delta_kb" else "RSS (GiB)"

    lines = [
        r'% Generated by kannolo-bench-paper/analysis/combined.py -- do not edit by hand.',
        r'\begin{tabular}{@{}lrrrrrrrrr@{}}',
        r'\toprule',
        r'& \multicolumn{3}{c}{QPS} & \multicolumn{3}{c}{' + fp_head + r'} '
        r'& \multicolumn{3}{c}{Build (s)} \\',
        r'\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(lr){8-10}',
        r'System' + ''.join(rf' & ${t}\%$' for t in TARGETS) * 3 + r' \\',
    ]
    for key, sel in selections:
        lines += [r'\midrule', rf'\multicolumn{{10}}{{@{{}}l}}{{{COLLECTIONS[key][0]}}} \\']
        for algo, entries, variant in rows_of(sel):
            name = MACRO[algo] + (r'$^{\dagger}$' if variant else '')
            if not variant and algo == "lorann" and sel["dataset"] in st.LEARN_SET_DATASETS:
                name = r'\lorann{} (learned)'
            qps, mem, build = [], [], []
            for t in TARGETS:
                row = entries.get(t)
                qps.append(f'{row["qps"]:.0f}' if row else '--')
                mem.append(f'{row[fp_field] / p1.MIB / 1024:.2f}' if row else '--')
                build.append(f'{row["build_time_s"]:.0f}' if row else '--')
            lines.append(r'\quad ' + name + ' & ' + ' & '.join(qps + mem + build) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular}']
    Path(out_path).write_text('\n'.join(lines) + '\n')
    return out_path


def configs_table(selections, out_path):
    lines = [
        r'% Generated by kannolo-bench-paper/analysis/combined.py -- do not edit by hand.',
        r'\begin{longtable}{@{}lr>{\raggedright\arraybackslash}p{0.65\linewidth}@{}}',
        r'\toprule',
        r'System & $t$ & Configuration \\',
        r'\midrule', r'\endhead',
    ]
    for key, sel in selections:
        lines.append(rf'\multicolumn{{3}}{{@{{}}l}}{{{COLLECTIONS[key][0]}}} \\')
        for algo, entries, variant in rows_of(sel):
            first_s = True
            for t in TARGETS:
                row = entries.get(t)
                if row is None:
                    continue
                name = (r'\quad ' + MACRO[algo] + (r'$^{\dagger}$' if variant else '')) if first_s else ''
                first_s = False
                cfg = tex_escape(config_string(algo, row))
                lines.append(rf'{name} & {t} & \texttt{{\scriptsize {cfg}}} \\')
        lines.append(r'\midrule')
    lines[-1] = r'\bottomrule'
    lines.append(r'\end{longtable}')
    Path(out_path).write_text('\n'.join(lines) + '\n')
    return out_path


PANEL_IN = 4.0
LEGEND_SIDE_IN = 3.6


def frontier_grid(selections, out_dir, series, legend_side):
    """The accuracy/QPS frontier of every collection as one row of square panels, with one legend.

    With `legend_side`, the legend is a column to the right of the row, one entry per line.
    Otherwise it is a single line below the row. Only the first panel carries the y-label, because
    every panel's y-axis is QPS; only the scales differ.
    """
    n = len(selections)
    extra_w = LEGEND_SIDE_IN if legend_side else 0
    fig, axes = plt.subplots(1, n, figsize=(PANEL_IN * n + extra_w, PANEL_IN),
                             squeeze=False)
    handles = {}
    for i, (ax, (key, sel)) in enumerate(zip(axes.flat, selections)):
        for algo in st.GRAPH_BAND:
            picks = sorted(sel["per_accuracy"].get(algo) or [], key=lambda r: r["accuracy_at_k"])
            if not picks:
                continue
            xs = [r["accuracy_at_k"] for r in picks]
            ys = [r["qps"] for r in picks]
            colour, marker = st.series_colour(algo), st.series_marker(algo)
            ax.plot(xs, ys, color=colour, linewidth=st.STYLE['line_width'], alpha=0.85)
            ax.scatter(xs, ys, color='white', marker=marker,
                       s=(st.STYLE['marker_size'] * 1.4) ** 2, edgecolor='none', zorder=2)
            h_ = ax.scatter(xs, ys, color=colour, marker=marker, s=st.STYLE['marker_size'] ** 2,
                            edgecolor='black', linewidth=0.5, zorder=3)
            handles.setdefault(st.DISPLAY[algo], h_)
        st.apply_axes_style(ax, title=COLLECTIONS[key][1], xlabel=r'Accuracy@10 (\%)',
                            ylabel='QPS' if i == 0 else None)
        ax.set_xlim(89.5, 100.5)
        ax.set_xticks([90, 95, 100])
        ax.set_ylim(0, None)
    order = [st.DISPLAY[a] for a in st.GRAPH_BAND if st.DISPLAY[a] in handles]
    legend = dict(frameon=True, fancybox=False, edgecolor='0.8', fontsize=st.STYLE['legend_size'])
    W, H = fig.get_figwidth(), fig.get_figheight()
    labels = [st.tex_label(l) for l in order]
    if legend_side:
        fig.tight_layout(rect=(0, 0, 1 - extra_w / W, 1))
        fig.legend([handles[l] for l in order], labels, ncol=1, loc='center left',
                   bbox_to_anchor=(1 - extra_w / W + 0.005, 0.55), **legend)
    else:
        st.legend_under_axes(fig, [handles[l] for l in order], labels, ncol=len(order),
                             columnspacing=1.2, handletextpad=0.3)
    return st.save_figure(fig, f'fig_frontier_{series}', out_dir)


TRADEOFF_VARIANTS = {"kannolo-rerank-ext8"}

LADDER_125 = [m * 10 ** e for e in range(-1, 6) for m in (1, 2, 5)]


def tradeoff_grid(selections, out_dir, series, legend_side, target="95"):
    """Footprint against QPS at one accuracy target, one point per system, one panel per collection.

    Every series is drawn, including those left out of the frontier figure (GRAPH_BAND). With the
    target fixed, each system is a single point, so no curve is flattened. Dotted diagonals mark
    constant QPS per GiB. The target is 95% because several systems do not reach 99%.
    """
    n = len(selections)
    extra_w = LEGEND_SIDE_IN if legend_side else 0
    fig, axes = plt.subplots(1, n, figsize=(PANEL_IN * n + extra_w, PANEL_IN),
                             squeeze=False)
    handles = {}
    for i, (ax, (key, sel)) in enumerate(zip(axes.flat, selections)):
        algos = [a for a in st.SERIES_ORDER if sel["per_target"].get(a)]
        fp_field, _ = p1._footprint_field(sel["per_target"], algos, (90, 95, 99))
        xs, ys = [], []
        variants = {a: e for a, e in (sel.get("per_target_variants") or {}).items()
                    if e and a in TRADEOFF_VARIANTS}
        for algo in algos + sorted(variants):
            row = (sel["per_target"].get(algo) or variants.get(algo) or {}).get(target)
            if row is None:
                continue
            x, y = row[fp_field] / p1.MIB / 1024, row["qps"]
            xs.append(x)
            ys.append(y)
            h_ = ax.scatter([x], [y], color=st.series_colour(algo), marker=st.series_marker(algo),
                            s=(st.STYLE['marker_size'] * 1.5) ** 2, edgecolor='black',
                            linewidth=0.6, zorder=4 if algo in variants else 3)
            handles.setdefault(st.DISPLAY[algo], h_)
        ax.set_xscale('log')
        ax.set_yscale('log')
        x0, x1 = min(xs) / 1.6, max(xs) * 1.6
        y0, y1 = min(ys) / 1.8, max(ys) * 1.8
        ax.set_xlim(x0, x1)
        ax.set_ylim(y0, y1)
        lo, hi = math.floor(math.log10(y0 / x1)), math.ceil(math.log10(y1 / x0))
        for k in range(lo, hi + 1):
            c = 10 ** k
            ax.plot([x0, x1], [c * x0, c * x1], color='0.45', linestyle=':', linewidth=1.0,
                    zorder=1)
            xl = min(x1 / 1.15, y1 / 1.25 / c)
            if xl > x0 * 1.3 and c * xl > y0 * 1.3:
                ax.text(xl, c * xl, f'{c:g}/GiB', fontsize=st.STYLE['tick_size'] - 4, color='0.35',
                        ha='right', va='bottom', rotation=0, zorder=2)
        st.apply_axes_style(ax, title=COLLECTIONS[key][1],
                            xlabel='Memory (GiB)' if fp_field == "uss_delta_kb" else 'RSS (GiB)',
                            ylabel=f'QPS at {target}\\%' if i == 0 else None,
                            xscale='log', yscale='log')
        p1.name_log_ticks(ax, 'x', xs, pad_lo=1 / 1.6, pad_hi=1.6, ladder=LADDER_125)
        p1.name_log_ticks(ax, 'y', ys, pad_lo=1 / 1.8, pad_hi=1.8, ladder=LADDER_125)
        ax.set_xlim(x0, x1)
        ax.set_ylim(y0, y1)
    order = [st.DISPLAY[a] for a in st.SERIES_ORDER if st.DISPLAY[a] in handles]
    order += sorted(l for l in handles if l not in order)
    legend = dict(frameon=True, fancybox=False, edgecolor='0.8', fontsize=st.STYLE['legend_size'])
    W, H = fig.get_figwidth(), fig.get_figheight()
    labels = [st.tex_label(l) for l in order]
    if legend_side:
        fig.tight_layout(rect=(0, 0, 1 - extra_w / W, 1))
        fig.legend([handles[l] for l in order], labels, ncol=1, loc='center left',
                   bbox_to_anchor=(1 - extra_w / W + 0.005, 0.55), **legend)
    else:
        ncol = len(order) if len(order) <= 8 else -(-len(order) // 2)
        st.legend_under_axes(fig, [handles[l] for l in order], labels, ncol=ncol,
                             columnspacing=1.0, handletextpad=0.2)
    return st.save_figure(fig, f'fig_tradeoff_{series}', out_dir)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--series", required=True, choices=["dense", "sparse"])
    ap.add_argument("--selection", nargs="+", required=True, metavar="COLLECTION=JSON",
                    help="in the order the paper lists the collections")
    ap.add_argument("--out-dir", required=True, help="output directory for the figures")
    ap.add_argument("--table-dir", required=True, help="output directory for the two table bodies")
    ap.add_argument("--legend", choices=["below", "side"], default=None,
                    help="legend below the row on one line, or in a column beside it "
                         "(default: below for dense, side for sparse)")
    args = ap.parse_args()

    if args.series == "sparse":
        st.use_sparse()
    st.configure()
    selections = []
    for item in args.selection:
        key, path = item.split("=", 1)
        if key not in COLLECTIONS:
            raise SystemExit(f"combined: unknown collection {key!r}; known: {sorted(COLLECTIONS)}")
        selections.append((key, json.loads(Path(path).read_text())))

    tdir = Path(args.table_dir)
    tdir.mkdir(parents=True, exist_ok=True)
    for path in (results_table(selections, tdir / f'results_{args.series}.tex'),
                 configs_table(selections, tdir / f'configs_{args.series}.tex'),
                 tradeoff_grid(selections, args.out_dir, args.series,
                               (args.legend or ("below" if args.series == "dense" else "side"))
                               == "side"),
                 frontier_grid(selections, args.out_dir, args.series,
                               (args.legend or ("below" if args.series == "dense" else "side"))
                               == "side")):
        print(path)


if __name__ == "__main__":
    main()
