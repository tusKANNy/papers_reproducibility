"""Tail latency of the reported configurations (paper, Table B.3): 99th-percentile latency at 95
and 99% accuracy and its ratio to the median.

Dense: VIBE's per-query times of the best pass (results/tail/dense.tsv, from tail_dense.py).
Sparse: each query timed inside the search tool over the timed passes of the reported
configuration, in-process for PyANN (results/tail/sparse.jsonl). LSP and SINDI time only whole
passes and are not included.

    python analysis/tail_table.py <out.tex>
"""
import csv, json, os, sys

R = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "results", "tail")
D = {}
for r in csv.DictReader(open(os.path.join(R, "dense.tsv")), delimiter="\t"):
    D[(r["dataset"], r["algo"], int(r["target"]))] = (float(r["p99_us"]), float(r["p99_over_p50"]))
S = {}
for l in open(os.path.join(R, "sparse.jsonl")):
    r = json.loads(l)
    S[(r["dataset"], r["algo"], r["target"])] = (r["p99_us"], r["p99_over_p50"])

def cell(v):
    if v is None: return "\\multicolumn{2}{c}{--}"
    p99, ratio = v
    p = f"{p99:,.0f}".replace(",", "\\,")
    return f"${p}$ & {{\\scriptsize $({ratio:.1f})$}}"

dense_cols = ["agnews-mxbai-1024-euclidean", "msmarco-qwen-1024-normalized",
              "dpr-jina-768-normalized", "laion-clip-512-normalized"]
dense_rows = [("\\kannolohnsw", "kannolo"), ("\\kannolorerank", "kannolo-rerank"),
              ("\\quad + ext-8", "kannolo-rerank-ext8"), ("\\hnswlib", "hnswlib"),
              ("\\glass", "glass"), ("\\symphonyqg", "symphonyqg"), ("\\lorann", "lorann"),
              ("\\rabitqhnsw", "rabitq-hnsw"), ("\\svsleanvec", "vamana-leanvec(svs)")]
sparse_cols = ["s1-msmarco-splade-v3", "s2-nq-cocondenser", "s4-msmarco-esplade"]
sparse_rows = [("\\kannolohnsw", "kannolo-hnsw"), ("\\kannolorerank", "kannolo-hnsw-rerank"),
               ("\\seismic", "seismic"), ("\\seismicw", "seismic-wave"), ("\\pyann", "pyanns")]
spec = "@{}l" + "@{\\hspace{7pt}}".join(["r@{\\,}l"] * 8) + "@{}"
out = ["% Generated by kannolo-bench-paper/analysis/tail_table.py -- do not edit by hand.",
       f"\\begin{{tabular}}{{{spec}}}", "\\toprule"]
out.append(" & " + " & ".join(f"\\multicolumn{{4}}{{c}}{{{n}}}" for n in
           ["\\agnews", "\\msmarcoqwen", "\\dpr", "\\laion"]) + " \\\\")
out.append("".join(f"\\cmidrule(lr){{{2+4*i}-{5+4*i}}}" for i in range(4)))
out.append(" & " + " & ".join(["\\multicolumn{2}{c}{$95\\%$} & \\multicolumn{2}{c}{$99\\%$}"] * 4) + " \\\\")
out.append("\\midrule")
for label, a in dense_rows:
    out.append(label + " & " + " & ".join(cell(D.get((ds, a, t))) for ds in dense_cols for t in (95, 99)) + " \\\\")
out.append("\\midrule")
out.append(" & " + " & ".join(f"\\multicolumn{{4}}{{c}}{{{n}}}" for n in ["\\msmarcosplade", "\\nq", "\\msmarcoesplade"]) + " & \\multicolumn{4}{c}{} \\\\")
out.append("".join(f"\\cmidrule(lr){{{2+4*i}-{5+4*i}}}" for i in range(3)))
out.append(" & " + " & ".join(["\\multicolumn{2}{c}{$95\\%$} & \\multicolumn{2}{c}{$99\\%$}"] * 3) + " & \\multicolumn{4}{c}{} \\\\")
out.append("\\midrule")
for label, a in sparse_rows:
    out.append(label + " & " + " & ".join(cell(S.get((ds, a, t))) for ds in sparse_cols for t in (95, 99)) + " & \\multicolumn{4}{c}{} \\\\")
out += ["\\bottomrule", "\\end{tabular}"]
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print("\n".join(out))
